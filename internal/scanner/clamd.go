func (e *Engine) ensureClamd(ctx context.Context) error {
	e.clamdMu.Lock()
	defer e.clamdMu.Unlock()

	if e.clamdscanPath() == "" || e.clamdPath() == "" {
		return fmt.Errorf("clamd/clamdscan нет в runtime")
	}
	if e.socketReady() {
		return nil
	}

	base, err := os.UserConfigDir()
	if err != nil {
		base = os.TempDir()
	}
	dir := filepath.Join(base, "yagaaegis", "clamd")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	e.confPath = filepath.Join(dir, "clamd.conf")
	var conf string
	if runtime.GOOS == "windows" {
		e.socketPath = "127.0.0.1:3318"
		conf = fmt.Sprintf(`# generated by YagaAegis — do not edit
Foreground true
TCPSocket 3318
TCPAddr 127.0.0.1
DatabaseDirectory %s
MaxDirectoryRecursion 20
ExitOnOOM true
`, filepath.ToSlash(e.DatabaseDir))
	} else {
		e.socketPath = filepath.Join(dir, "clamd.sock")
		_ = os.Remove(e.socketPath)
		conf = fmt.Sprintf(`# generated by YagaAegis — do not edit
Foreground true
LocalSocket %s
FixStaleSocket true
DatabaseDirectory %s
MaxDirectoryRecursion 20
ExitOnOOM true
`, e.socketPath, e.DatabaseDir)
	}
	if e.CertsDir != "" {
		conf += fmt.Sprintf("CVDCertsDirectory %s\n", e.CertsDir)
	}
	if err := os.WriteFile(e.confPath, []byte(conf), 0o644); err != nil {
		return err
	}

	cmd := exec.CommandContext(context.Background(), e.clamdPath(), "-c", e.confPath)
	cmd.Dir = filepath.Dir(e.clamdPath())
	cmd.Env = e.clamEnv()
	cmd.Stdout = nil
	cmd.Stderr = nil
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("старт clamd: %w", err)
	}
	e.clamdCmd = cmd

	deadline := time.Now().Add(45 * time.Second)
	for time.Now().Before(deadline) {
		select {
		case <-ctx.Done():
			e.stopClamdLocked()
			return ctx.Err()
		default:
		}
		if e.socketReady() {
			if e.log != nil {
				e.log.Info("clamd готов", "socket", e.socketPath)
			}
			go e.reapClamd()
			return nil
		}
		time.Sleep(150 * time.Millisecond)
	}
	e.stopClamdLocked()
	return fmt.Errorf("clamd не поднялся за 45с")
}

func (e *Engine) socketReady() bool {
	if e.socketPath == "" {
		return false
	}
	network := "unix"
	addr := e.socketPath
	if runtime.GOOS == "windows" || strings.Contains(e.socketPath, ":") {
		network = "tcp"
		addr = e.socketPath
	}
	c, err := net.DialTimeout(network, addr, 200*time.Millisecond)
	if err != nil {
		return false
	}
	_ = c.Close()
	return true
}

func (e *Engine) reapClamd() {
	if e.clamdCmd == nil || e.clamdCmd.Process == nil {
		return
	}
	_ = e.clamdCmd.Wait()
}

func (e *Engine) stopClamdLocked() {
	if e.clamdCmd != nil && e.clamdCmd.Process != nil {
		_ = e.clamdCmd.Process.Kill()
		e.clamdCmd = nil
	}
	if e.socketPath != "" {
		_ = os.Remove(e.socketPath)
	}
}

// StopClamd — при выходе из приложения.
func (e *Engine) StopClamd() {
	e.clamdMu.Lock()
	defer e.clamdMu.Unlock()
	e.stopClamdLocked()
}

func (e *Engine) scanViaClamd(ctx context.Context, abs string, isDir bool) (out []byte, err error) {
	if err := e.ensureClamd(ctx); err != nil {
		return nil, err
	}
	args := []string{"--fdpass", "--infected", "--config-file=" + e.confPath}
	// recursive через clamd уже по конфигу; -r у clamdscan для каталогов
	if isDir {
		args = append(args, "-r")
	}
	args = append(args, abs)
	cmd := exec.CommandContext(ctx, e.clamdscanPath(), args...)
	cmd.Dir = filepath.Dir(e.clamdscanPath())
	cmd.Env = e.clamEnv()
	return cmd.CombinedOutput()
}

// PreferClamd — есть ли бинарники для ускоренного режима.
func (e *Engine) PreferClamd() bool {
	return e.clamdPath() != "" && e.clamdscanPath() != ""
}

// Warmup поднимает clamd заранее (старт приложения).
func (e *Engine) Warmup(ctx context.Context) {
	if !e.PreferClamd() {
		return
	}
	e.warmOnce.Do(func() {
		_ = e.ensureClamd(ctx)
	})
}
